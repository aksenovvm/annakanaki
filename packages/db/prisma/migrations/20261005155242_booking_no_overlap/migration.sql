-- Защита от двойной записи (docs/spec.md, раздел 6).
--
-- Проверки в коде недостаточно: два человека могут одновременно нажать «Записаться» на одно время.
-- Оба запроса проверят «свободно?» → «да» и оба попробуют сохранить запись.
-- Поэтому последнее слово — за PostgreSQL: он не даст сохранить две подтверждённые записи
-- одного мастера с пересекающимся временем. Вторая получит ошибку 23P01, а API ответит 409 SLOT_TAKEN.

-- Расширение, которое позволяет в одном ограничении сравнивать и обычные значения (barber_id =),
-- и диапазоны времени (&& — «пересекаются»).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Время записи как один диапазон [начало, конец). Считается автоматически из starts_at и ends_at.
-- '[)' — начало включено, конец нет: запись 10:00–11:00 и запись 11:00–12:00 НЕ пересекаются.
ALTER TABLE "bookings"
ADD COLUMN "time_range" tstzrange
GENERATED ALWAYS AS (tstzrange("starts_at", "ends_at", '[)')) STORED;

-- Само правило: у одного мастера не может быть двух подтверждённых записей, чьё время пересекается.
-- Отменённые, завершённые и неявки не мешают.
ALTER TABLE "bookings"
ADD CONSTRAINT "bookings_no_overlap"
EXCLUDE USING gist (
  "barber_id" WITH =,
  "time_range" WITH &&
)
WHERE ("status" = 'confirmed');
